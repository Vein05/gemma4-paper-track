#!/usr/bin/env python3
"""Build paper/references.bib from citations.md (research/CLAUDE.md: no citations from memory).

Papers: every citations.md row with an arXiv link. Title, authors and year are fetched again from the arXiv API, not
copied from the table, and checked against the table; a mismatch stops the build. The venue note comes from the
API's journal_ref, else from the table's venue column (itself taken from the arXiv comment), else none.
Data and software: rows of the second table, as @misc with the maintainer, revision and link shown there.

  python3 build_bib.py            # writes ../paper/references.bib
"""
import os, re, sys, time, urllib.request, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
CIT = os.path.join(HERE, "..", "citations.md")
OUT = os.path.join(HERE, "..", "paper", "references.bib")
NS = {"a": "http://www.w3.org/2005/Atom", "x": "http://arxiv.org/schemas/atom"}


def rows():
    papers, software, table = [], [], 0
    for line in open(CIT):
        if line.startswith("| Key |"):
            table += 1
            continue
        if not line.startswith("| ") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        (papers if table == 1 else software).append(cells)
    return papers, software


def noted():
    """Keys with a line in citations.md's Notes that starts '<key>:' and explains a disagreement with the arXiv API."""
    return set(re.findall(r"^(\w+): .*?(?:arXiv's metadata|API)", open(CIT).read(), flags=re.M))


def fetch(ids):
    url = "http://export.arxiv.org/api/query?max_results=100&id_list=" + ",".join(ids)
    for attempt in range(5):
        try:
            return ET.fromstring(urllib.request.urlopen(url, timeout=60).read())
        except Exception as e:  # the API returns 503 under load
            print(f"arXiv API: {e}; retry {attempt + 1}", file=sys.stderr)
            time.sleep(10 * (attempt + 1))
    sys.exit("arXiv API unavailable")


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def main():
    papers, software = rows()
    ids = {}
    for key, title, authors, venue, link, _ in papers:
        m = re.search(r"arxiv\.org/abs/([\d.]+)", link)
        if not m:
            sys.exit(f"{key}: no arXiv link; add it by hand from its primary source")
        ids[m.group(1)] = (key, title, authors, venue)
    feed = fetch(list(ids))
    entries, bad = {}, []
    for e in feed.findall("a:entry", NS):
        aid = re.sub(r"v\d+$", "", e.find("a:id", NS).text.rsplit("/", 1)[-1])
        key, t_tab, a_tab, venue = ids[aid]
        title = norm(e.find("a:title", NS).text)
        authors = [norm(a.find("a:name", NS).text) for a in e.findall("a:author", NS)]
        if title != norm(t_tab) or authors != [norm(a) for a in a_tab.split(";")]:
            if key in noted():  # a documented metadata fault (citations.md Notes, "<key>: ..."): the table's list stands
                print(f"{key}: table and API disagree; using the table's author list (see citations.md Notes)", file=sys.stderr)
                authors = [norm(a) for a in a_tab.split(";")]
            else:
                bad.append(key)
        jref = e.find("x:journal_ref", NS)
        note = norm(jref.text) if jref is not None else (venue.split(";")[0].strip()
                                                        if not venue.startswith("arXiv preprint") else "")
        cat = e.find("x:primary_category", NS).get("term")
        f = [f"  title = {{{{{title}}}}}", f"  author = {{{' and '.join(authors)}}}",
             f"  year = {{{e.find('a:published', NS).text[:4]}}}", f"  eprint = {{{aid}}}",
             "  archivePrefix = {arXiv}", f"  primaryClass = {{{cat}}}", f"  url = {{https://arxiv.org/abs/{aid}}}"]
        if note:
            f.append(f"  note = {{{note}}}")
        entries[key] = "@misc{" + key + ",\n" + ",\n".join(f) + "\n}"
    missing = [v[0] for v in ids.values() if v[0] not in entries]
    if bad or missing:
        sys.exit(f"table and arXiv API disagree: {bad}; not returned by the API: {missing}")
    for key, name, maint, rev, link, verified in software:
        m = re.match(r"(.*?)\s*\((.*)\)$", name)
        title, kind = (m.group(1), m.group(2)) if m else (name, "")
        rev = rev.strip("`")
        kind = re.sub(r"`([^`]+)`", r"\\texttt{\1}", kind)
        note = ([kind[0].upper() + kind[1:]] if kind else []) + (
            [f"revision {rev}"] if re.fullmatch(r"[0-9a-f]{7,40}", rev) else []) + [f"accessed {verified.split()[0]}"]
        f = [f"  title = {{{{{title}}}}}", f"  author = {{{{{maint}}}}}", f"  howpublished = {{\\url{{{link}}}}}",
             f"  note = {{{'; '.join(note)}}}"]
        entries[key] = "@misc{" + key + ",\n" + ",\n".join(f) + "\n}"
    with open(OUT, "w") as o:
        o.write("% Generated by scripts/build_bib.py from citations.md and the arXiv API. Do not edit by hand.\n\n")
        o.write("\n\n".join(entries[k] for k in sorted(entries)) + "\n")
    print(f"{len(entries)} entries -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
